# version
# --------------------------------------------------------------------------


def project_version() -> str:
    """Read the version from pyproject, so there is a single source of it."""
    text = (ROOT / "pyproject.toml").read_text(encoding="utf-8")
    match = re.search(r'^version = "([^"]+)"', text, re.M)
    if not match:
        raise SystemExit("could not find a version in pyproject.toml")
    return match.group(1)


def write_version_resource(version: str) -> None:
    """Generate the Windows version resource embedded in koe.exe.

    Generated rather than committed because it restates the version. Without
    it the file-properties dialog shows a blank publisher, which is exactly
    what an unsigned binary from an unknown source looks like — and this one is
    already unsigned.
    """
    parts = [int(p) for p in version.split(".")] + [0, 0, 0, 0]
    quad = ", ".join(str(p) for p in parts[:4])

    fields = [*VERSION_FIELDS, ("FileVersion", version), ("ProductVersion", version)]
    entries = ",\n         ".join(f'StringStruct("{k}", "{v}")' for k, v in sorted(fields))
    tables = ",\n      ".join(
        f'StringTable(\n        "{code}",\n        [{entries}])' for code in LANGUAGE_CODES
    )

    content = (
        "# Generated by packaging/build.py - do not edit.\n"
        "VSVersionInfo(\n"
        "  ffi=FixedFileInfo(\n"
        f"    filevers=({quad}),\n"
        f"    prodvers=({quad}),\n"
        "    mask=0x3f, flags=0x0, OS=0x40004, fileType=0x1, subtype=0x0, date=(0, 0)\n"
        "  ),\n"
        "  kids=[\n"
        "    StringFileInfo([\n"
        f"      {tables}\n"
        "    ]),\n"
        '    VarFileInfo([VarStruct("Translation", [1041, 1200, 1033, 1200])])\n'
        "  ]\n"
        ")\n"
    )
    (PACKAGING / "version_info.txt").write_text(content, encoding="utf-8")


def sync_installer_version(version: str) -> None:
    """Keep the Inno script's version in step with pyproject."""
    path = PACKAGING / "koe.iss"
    text = path.read_text(encoding="utf-8")
    updated = re.sub(r'(#define AppVersion ")[^"]+(")', r"\g<1>" + version + r"\g<2>", text)
    if updated != text:
        path.write_text(updated, encoding="utf-8")
        print(f"  synced installer version to {version}")


