# build steps
# --------------------------------------------------------------------------


def build_web() -> None:
    """Rebuild the browser bundle so the app cannot ship a stale UI."""
    npm = shutil.which("npm")
    if npm is None:
        print("! npm not found - using the committed web/dist bundle")
        if not (ROOT / "web" / "dist" / "app.js").exists():
            raise SystemExit("no committed bundle and no npm; cannot continue")
        return
    web = ROOT / "web"
    if not (web / "node_modules").is_dir():
        run([npm, "ci", "--no-audit", "--no-fund"], cwd=web)
    run([npm, "run", "build"], cwd=web)


def build_app(*, with_japanese: bool, clean: bool) -> None:
    env = dict(os.environ)
    env["KOE_BUILD_JAPANESE"] = "1" if with_japanese else "0"

    command = [
        sys.executable,
        "-m",
        "PyInstaller",
        str(PACKAGING / "koe.spec"),
        "--noconfirm",
        "--distpath",
        str(DIST),
        "--workpath",
        str(BUILD),
    ]
    if clean:
        command.append("--clean")
    run(command, cwd=ROOT, env=env)


def directory_size(path: Path) -> int:
    return sum(f.stat().st_size for f in path.rglob("*") if f.is_file())


def verify() -> None:
    """Start the built app headless and confirm it serves real requests.

    A frozen build fails at *import* time far more often than at build time —
    a missing hidden import produces a perfectly successful build and an
    executable that closes instantly. Catching that here rather than from a
    user is the entire point of this step.
    """
    if not APP_EXE.exists():
        raise SystemExit(f"expected {APP_EXE} to exist")

    print("\n-- verifying the built application --", flush=True)
    env = dict(os.environ)
    env["KOE_DESKTOP_HEADLESS"] = "1"  # start the server, skip the window
    port_file = BUILD / "port.txt"
    env["KOE_DESKTOP_PORT_FILE"] = str(port_file)
    port_file.unlink(missing_ok=True)

    process = subprocess.Popen(
        [str(APP_EXE)],
        env=env,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        encoding="utf-8",
        errors="replace",
    )
    try:
        port: int | None = None
        for _ in range(900):  # up to 90s; a cold first run unpacks a lot
            if port_file.exists():
                try:
                    port = int(port_file.read_text(encoding="utf-8").strip())
                    break
                except ValueError:
                    pass
            if process.poll() is not None:
                output = process.stdout.read() if process.stdout else ""
                raise SystemExit(f"the application exited during startup:\n{output}")
            time.sleep(0.1)

        if port is None:
            raise SystemExit("the application never reported a port")

        try:
            with urllib.request.urlopen(f"http://127.0.0.1:{port}/health", timeout=20) as response:
                body = json.loads(response.read())
        except (urllib.error.URLError, TimeoutError) as exc:
            raise SystemExit(f"health check failed: {exc}") from exc

        print(f"   health:   {body['status']}   japanese: {body['japanese_tokenizer']}")
        if body["status"] != "ok":
            raise SystemExit(f"unhealthy: {body}")

        # Exercise the real pipeline, not just the health endpoint. A bundle
        # can be healthy and still be missing the corpus or the dictionary.
        request = urllib.request.Request(
            f"http://127.0.0.1:{port}/v1/transcribe",
            data=json.dumps({"meeting": "quarterly-ja", "priority": "quality"}).encode(),
            headers={"Content-Type": "application/json"},
        )
        with urllib.request.urlopen(request, timeout=30) as response:
            transcript = json.loads(response.read())
        segments = len(transcript.get("segments", []))
        if segments == 0:
            raise SystemExit("the bundled pipeline produced no segments")
        print(f"   pipeline: {segments} segments via {transcript['routed_to']}")

        # And fetch the page the window will actually show. This check exists
        # because its absence shipped: the resource path was wrong for a frozen
        # build, so `/` served the "build the client" placeholder while every
        # check above passed. A binary that answers /health is not a binary
        # that runs the product.
        with urllib.request.urlopen(f"http://127.0.0.1:{port}/", timeout=20) as response:
            page = response.read().decode("utf-8", "replace")
        if "Build the client" in page or 'id="toggle"' not in page:
            raise SystemExit(
                "the bundle serves the placeholder page, not the web client — "
                "the client is missing from the bundle or _web_root() is wrong"
            )

        # The bundle is served from /static; a 200 on the page with a 404 on
        # its script is the same failure one layer down.
        with urllib.request.urlopen(f"http://127.0.0.1:{port}/static/app.js", timeout=20) as res:
            script_bytes = len(res.read())
        if script_bytes < 1000:
            raise SystemExit(f"/static/app.js is {script_bytes} bytes; the bundle is not there")
        print(f"   client:   index.html + app.js ({script_bytes / 1024:,.0f} KB)")
    finally:
        process.terminate()
        try:
            process.wait(timeout=15)
        except subprocess.TimeoutExpired:
            process.kill()


def build_installer() -> Path | None:
    """Compile the Inno Setup installer, if the compiler is present."""
    compiler = next((p for p in _inno_candidates() if p.exists()), None)
    if compiler is None:
        print(
            "\n! Inno Setup 6 not found - skipping the installer.\n"
            "  Install it (winget install JRSoftware.InnoSetup) and re-run\n"
            "  with --installer, or ship dist/koe as a portable folder."
        )
        return None
    run([str(compiler), str(PACKAGING / "koe.iss")], cwd=ROOT)
    produced = sorted(DIST.glob("koe-setup-*.exe"))
    return produced[-1] if produced else None


def write_checksum(target: Path) -> str:
    """Write `SHA256SUMS.txt` beside `target` and return the digest.

    The installer is unsigned — a code-signing certificate is a recurring cost
    this project does not carry — so Windows will show a SmartScreen warning on
    a downloaded copy. A published digest is what turns "trust me" into
    something a user can actually check before they click through it, and it is
    the only integrity guarantee an unsigned binary has.
    """
    digest = hashlib.sha256(target.read_bytes()).hexdigest()
    # `sha256sum -c` / `Get-FileHash` format: digest, two spaces, bare name.
    (target.parent / "SHA256SUMS.txt").write_text(f"{digest}  {target.name}\n", encoding="utf-8")
    return digest


