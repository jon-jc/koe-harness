"""Build the koe desktop application.

    python packaging/build.py                 # full build
    python packaging/build.py --no-japanese   # smaller, character segmentation
    python packaging/build.py --installer     # also produce Setup.exe

Does four things a bare `pyinstaller` invocation does not:

**Derives the version from one place.** The Windows version resource and the
installer script both restate the version, and a second hand-maintained copy of
a version number is a copy that goes stale.

**Builds the web client first.** The bundle is committed, but rebuilding here
means a packaged app can never ship a stale UI — the failure that produces a
bug report about a fix made weeks ago.

**Verifies the artifact.** A PyInstaller build succeeds happily while producing
an executable that dies on launch from a missing hidden import. The build is
not finished until the thing has been started and has served a real request.

**Reports what it produced.** Size is a real property of a desktop app, and one
that quietly triples when a dependency is added.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PACKAGING = ROOT / "packaging"
DIST = ROOT / "dist"
BUILD = ROOT / "build"
APP_DIR = DIST / "koe"
APP_EXE = APP_DIR / "koe.exe"

VERSION_FIELDS = [
    ("CompanyName", "jon-jc"),
    ("FileDescription", "koe - bilingual voice AI harness"),
    ("InternalName", "koe"),
    ("LegalCopyright", "MIT License"),
    ("OriginalFilename", "koe.exe"),
    ("ProductName", "koe"),
]

# Japanese (ja-JP) first, then English (en-US), both Unicode. A Japanese
# Windows install reads the ja-JP table and shows the properties in place.
LANGUAGE_CODES = ("041104b0", "040904b0")


def _inno_candidates() -> list[Path]:
    """Where ISCC.exe might be.

    winget installs Inno Setup per-user by default, which puts it under
    LOCALAPPDATA rather than Program Files — a location most build scripts
    miss, and then report the compiler as absent on a machine that has it.
    """
    paths = [
        Path(r"C:\Program Files (x86)\Inno Setup 6\ISCC.exe"),
        Path(r"C:\Program Files\Inno Setup 6\ISCC.exe"),
    ]
    local = os.environ.get("LOCALAPPDATA")
    if local:
        paths.append(Path(local) / "Programs" / "Inno Setup 6" / "ISCC.exe")
    found = shutil.which("ISCC")
    if found:
        paths.insert(0, Path(found))
    return paths


def run(command: list[str], *, cwd: Path | None = None, env: dict[str, str] | None = None) -> None:
    printable = " ".join(command)
    print(f"\n$ {printable}", flush=True)
    result = subprocess.run(command, cwd=cwd, env=env, check=False)
    if result.returncode != 0:
        raise SystemExit(f"command failed ({result.returncode}): {printable}")


