def main() -> int:
    parser = argparse.ArgumentParser(description="Build the koe desktop application")
    parser.add_argument(
        "--no-japanese",
        action="store_true",
        help="exclude MeCab/unidic (~248MB smaller; character segmentation instead)",
    )
    parser.add_argument("--installer", action="store_true", help="also build Setup.exe")
    parser.add_argument("--skip-web", action="store_true", help="use the committed bundle")
    parser.add_argument("--skip-verify", action="store_true", help="do not launch the result")
    parser.add_argument("--clean", action="store_true", help="discard PyInstaller caches")
    args = parser.parse_args()

    if sys.platform != "win32":
        print(f"! building on {sys.platform}; the .exe target is Windows-only")

    started = time.time()

    version = project_version()
    print(f"building koe {version}")
    write_version_resource(version)
    sync_installer_version(version)

    if not args.skip_web:
        build_web()

    build_app(with_japanese=not args.no_japanese, clean=args.clean)

    if not args.skip_verify:
        verify()

    size_mb = directory_size(APP_DIR) / 1024 / 1024
    print("\n" + "=" * 66)
    print(f"  built  {APP_EXE}")
    print(f"  size   {size_mb:,.0f} MB  (japanese: {'no' if args.no_japanese else 'yes'})")
    print(f"  took   {time.time() - started:,.0f}s")

    if args.installer:
        installer = build_installer()
        if installer:
            print(f"  setup  {installer}  ({installer.stat().st_size / 1024 / 1024:,.0f} MB)")
            print(f"  sha256 {write_checksum(installer)}")
    print("=" * 66)
    return 0


if __name__ == "__main__":
    sys.exit(main())
